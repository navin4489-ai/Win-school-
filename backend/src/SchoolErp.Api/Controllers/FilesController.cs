using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Extensions.Options;
using SchoolErp.Application.Common;
using SchoolErp.Infrastructure.Services;

namespace SchoolErp.Api.Controllers;

public sealed class UploadedFileDto
{
    public string Url { get; init; } = string.Empty;
    public string Path { get; init; } = string.Empty;
    public string FileName { get; init; } = string.Empty;
    public string ContentType { get; init; } = string.Empty;
    public long SizeBytes { get; init; }
}

/// <summary>
/// Upload endpoint used for attendance photos and student documents.
///
/// Only an allow-list of content types is accepted and the size is capped by
/// <see cref="StorageOptions.MaxFileSizeBytes"/>. The stored file name is generated by
/// the storage layer, so an attacker cannot control the path on disk.
/// </summary>
[ApiController]
[Route("api/files")]
[Authorize]
public sealed class FilesController : ControllerBase
{
    private static readonly string[] AllowedContentTypes =
    {
        "image/jpeg", "image/png", "image/webp", "image/heic", "application/pdf"
    };

    private static readonly string[] AllowedExtensions = { ".jpg", ".jpeg", ".png", ".webp", ".heic", ".pdf" };

    private readonly IFileStorage _storage;
    private readonly StorageOptions _options;

    public FilesController(IFileStorage storage, IOptions<StorageOptions> options)
    {
        _storage = storage;
        _options = options.Value;
    }

    [HttpPost("upload")]
    [RequestSizeLimit(12 * 1024 * 1024)]
    public async Task<ActionResult<UploadedFileDto>> Upload(IFormFile file, CancellationToken ct)
    {
        if (file is null || file.Length == 0) return BadRequest(new { detail = "No file was uploaded." });

        if (file.Length > _options.MaxFileSizeBytes)
            return BadRequest(new
            {
                detail = $"The file is larger than the {_options.MaxFileSizeBytes / (1024 * 1024)} MB limit."
            });

        var extension = Path.GetExtension(file.FileName ?? string.Empty).ToLowerInvariant();
        if (!AllowedExtensions.Contains(extension))
            return BadRequest(new { detail = "Only JPG, PNG, WEBP, HEIC and PDF files are accepted." });

        var contentType = (file.ContentType ?? string.Empty).ToLowerInvariant();
        if (!AllowedContentTypes.Contains(contentType))
            return BadRequest(new { detail = $"The content type '{contentType}' is not accepted." });

        await using var stream = file.OpenReadStream();
        var stored = await _storage.SaveAsync(stream, file.FileName ?? "upload", contentType, ct);

        return Ok(new UploadedFileDto
        {
            Url = FileUrlSigner.SignStoredUrl(stored.Url) ?? string.Empty,
            Path = stored.Path,
            FileName = Path.GetFileName(file.FileName ?? "upload"),
            ContentType = contentType,
            SizeBytes = file.Length
        });
    }
}
